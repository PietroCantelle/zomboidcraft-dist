// ZomboidCraft - the "Caderno de Sobrevivência" and the crumpled recipe notes (KubeJS 6 / LootJS 2.x / Patchouli, Forge 1.20.1).
// EMI is creative-only (client_scripts/zc_emi_gamemode.js) and the vanilla recipe book is gone
// (startup_scripts/zc_no_recipe_book.js), so in survival recipes are found on paper:
//   kubejs:survival_journal - every survivor starts with it: a worn Patchouli book (zc_hair:caderno) whose pages
//                             unlock as recipes are stored in it (invisible advancements zc_recipes:learned/*)
//   kubejs:recipe_note      - loot; the first look fixes ONE recipe on it (prefers one the reader does not know yet).
//                             Using it stores the recipe in the notebook and the note is used up. A note whose
//                             recipe is already in your notebook stays in your hand: trade it or copy it.
// Notes can be copied: note + paper + black dye (or ink sac / charcoal) -> 2 notes.
//
// Two lists of recipes:
//   - the 56 essential ones (first steps, shelter, health, clothes...): zc_recipe_notes_list.js (hand-picked)
//   - 0.4.2: (almost) every other recipe of the pack, ~3500 notes for ~7000 items (one note = one recipe, or the
//     color/wood variations of the same thing), sorted in 16 themes: kubejs/config/zc_recipe_notes_all.json.
//     Pages and advancements of those live in the zc_hair jar. All generated by docs/tools/gen_recipe_notes_all.js.
// Loot notes carry a theme (NBT zc_theme) picked by the place (workshop -> Create/metal, kitchen -> food...); the
// recipe itself is only decided when the note is first read, among the ones that reader does not know yet.
// Rhino: no `const` inside functions that run more than once ("redeclaration of var"), hence `let`.
// Everything is wrapped in a function: KubeJS shares one global scope between script files.
(function () {
  const BOOK = 'zc_hair:caderno'   // book.json ships in zc_hair.jar (Patchouli only reads books from mod jars)
  const JOURNAL = 'kubejs:survival_journal'
  const NOTE = 'kubejs:recipe_note'
  const GIVEN = 'zc_journal_given'
  const ALL_JSON = 'kubejs/config/zc_recipe_notes_all.json'
  const ESSENTIAL = 'essencial'
  const Patchouli = Java.loadClass('vazkii.patchouli.api.PatchouliAPI')
  const RL = Java.loadClass('net.minecraft.resources.ResourceLocation')

  // ---------------------------------------------------------------- the notes that really work (rebuilt after /reload)
  // note = { key, entry, adv, theme, icon, size }
  let checkedFor = null, usable = [], byKey = {}, byTheme = {}
  function load(server) {
    let manager = server.recipeManager
    if (checkedFor === manager) return usable
    let raw = []
    // the zc_recipe_notes_list.js file loads after this one: only read it here, inside a handler
    ZC_RECIPE_NOTES.forEach(n => raw.push({ key: n[0], entry: n[1], adv: n[2], recipes: n[3], theme: ESSENTIAL, icon: n[0], size: 1 }))
    try {
      let json = JsonIO.read(ALL_JSON)
      json.notes.forEach(n => {
        let key = String(n[0]), theme = String(n[1])
        let recipes = []
        n[4].forEach(r => recipes.push(String(r)))
        raw.push({ key: 'x:' + key, entry: 'zc_hair:m_' + theme + '/' + key, adv: 'zc_recipes:learned/x/' + key,
          recipes: recipes, theme: theme, icon: String(n[2]), size: Number(n[3]) })
      })
    } catch (e) { console.error('[ZC] recipe notes: could not read ' + ALL_JSON + ': ' + e) }
    let missing = 0
    usable = []
    byKey = {}
    byTheme = {}
    raw.forEach(n => {
      if (!Item.exists(n.icon) || !n.recipes.every(id => manager.byKey(new RL(id)).isPresent())) { missing++; return }
      usable.push(n)
      byKey[n.key] = n
      if (!byTheme[n.theme]) byTheme[n.theme] = []
      byTheme[n.theme].push(n)
    })
    checkedFor = manager
    console.info(`[ZC] recipe notes: ${usable.length}/${raw.length} notes usable (${missing} missing)`)
    return usable
  }

  // ---------------------------------------------------------------- knowledge = the invisible advancements
  function knows(player, note) {
    let adv = player.server.advancements.getAdvancement(new RL(note.adv))
    return adv != null && player.advancements.getOrStartProgress(adv).isDone()
  }
  // a note the reader does not know: a few random tries first (cheap), then a full scan of the theme
  function freshIn(player, pool) {
    if (!pool || pool.length === 0) return null
    for (let i = 0; i < 40; i++) {
      let n = pool[Math.floor(Math.random() * pool.length)]
      if (!knows(player, n)) return n
    }
    let fresh = pool.filter(n => !knows(player, n))
    return fresh.length > 0 ? fresh[Math.floor(Math.random() * fresh.length)] : null
  }
  function pick(player, theme) {
    load(player.server)
    let pool = byTheme[theme]
    if (!pool) {
      // unread note without a theme (old loot, /give): the essentials first, then anything
      pool = byTheme[ESSENTIAL]
      let n = freshIn(player, pool)
      if (n) return n
      pool = usable
    }
    let n = freshIn(player, pool) || freshIn(player, usable)
    if (n) return n
    return pool && pool.length > 0 ? pool[Math.floor(Math.random() * pool.length)] : null
  }
  function itemKey(note) { return String(Item.of(note.icon).item.getDescriptionId()) }
  function nameOf(note) {
    let item = Text.translate(itemKey(note))
    return note.size > 1 ? Text.translate('zc.recipes.note_group', item) : item
  }
  function nameJson(note) {
    let item = { translate: itemKey(note) }
    let what = note.size > 1 ? { translate: 'zc.recipes.note_group', with: [item] } : item
    return JSON.stringify({ translate: 'zc.recipes.note_name', with: [what], italic: false })
  }

  // the client needs the advancement packet before Patchouli shows the page: open a few ticks later
  function openAt(player, entry) {
    player.server.scheduleInTicks(10, () => {
      try {
        if (entry) Patchouli.get().openBookEntry(player, new RL(BOOK), new RL(entry), 0)
        else Patchouli.get().openBookGUI(player, new RL(BOOK))
      } catch (e) { console.error('[ZC] recipe notes: could not open the notebook: ' + e) }
    })
  }

  // ---------------------------------------------------------------- using a note
  ItemEvents.rightClicked(NOTE, event => {
    let player = event.player
    let stack = event.item
    load(player.server)
    let id = stack.nbt && stack.nbt.contains('zc_recipes') ? String(stack.nbt.getString('zc_recipes')) : ''
    let theme = stack.nbt && stack.nbt.contains('zc_theme') ? String(stack.nbt.getString('zc_theme')) : ''
    let note = id ? byKey[id] : null
    if (!note) note = pick(player, theme)   // an unread note: decide what is written on it
    if (!note) {
      player.setStatusMessage(Text.translate('zc.recipes.empty').gray())
    } else if (knows(player, note)) {
      // already in the notebook: keep the note (now readable) to trade or copy
      if (!id) stack.nbt = { zc_recipes: note.key, display: { Name: nameJson(note) } }
      player.setStatusMessage(Text.translate('zc.recipes.already', nameOf(note)).gray())
    } else {
      player.unlockAdvancement(note.adv)
      stack.shrink(1)
      let count = usable.filter(n => n === note || knows(player, n)).length
      player.setStatusMessage(Text.translate('zc.recipes.learned', nameOf(note), String(count), String(usable.length)).gold())
      player.server.runCommandSilent(`playsound minecraft:item.book.page_turn player ${player.username}`)
      openAt(player, note.entry)
    }
    // KubeJS 6: cancel() ends the handler on the spot, so it must be the last call
    event.cancel()
  })

  ItemEvents.rightClicked(JOURNAL, event => {
    openAt(event.player, null)
    event.cancel()
  })

  // Every survivor starts with the notebook (players from before this update get it on their next login).
  PlayerEvents.loggedIn(event => {
    let player = event.player
    if (player.persistentData.getBoolean(GIVEN)) return
    player.persistentData.putBoolean(GIVEN, true)
    player.give(JOURNAL)
  })

  // ---------------------------------------------------------------- copying notes (trading recipes)
  ServerEvents.recipes(event => {
    event.shapeless('2x ' + NOTE, [NOTE, 'minecraft:paper', Ingredient.of(['#forge:dyes/black', 'minecraft:ink_sac', 'minecraft:charcoal'])])
      .modifyResult((grid, result) => {
        let note = grid.find(Item.of(NOTE))
        // an unread note copies into one unread note: no free random recipes
        if (!note || !note.nbt || !note.nbt.contains('zc_recipes')) return Item.of(NOTE)
        return result.withNBT(note.nbt)
      })
      .id('zomboidcraft:copy_recipe_note')
  })

  // ---------------------------------------------------------------- where to find them
  // A note in a chest only knows its THEME (one small loot entry per theme, not one per recipe): the recipe is
  // decided when it is read. [loot-table regex, chance, how many, { theme: weight }]
  // LootJS matches the WHOLE loot-table id, hence the .* around the words.
  const THEMES = ['create_forca', 'create_prensa', 'create_producao', 'create_avancado', 'engenharia', 'ferraria',
    'eletronica', 'seguranca', 'marcenaria', 'construcao', 'tecidos', 'culinaria', 'decoracao', 'enfermagem', 'mecanica',
    'sobrevivencia']
  function noteOf(theme) {
    let name = JSON.stringify({ translate: 'zc.recipes.note_theme', with: [{ translate: 'zc.recipes.theme.' + theme }], italic: false })
    return Item.of(NOTE, { zc_theme: theme, display: { Name: name } })
  }
  function weighted(w) {
    let out = [LootEntry.of(Item.of(NOTE)).withWeight(w[ESSENTIAL] || 3)]   // essentials: no theme on the note
    THEMES.forEach(t => out.push(LootEntry.of(noteOf(t)).withWeight(w[t] || 1)))
    return out
  }
  const PLACES = [
    // workshops, garages, factories, metro, power plant: Create, metal, machines, cars
    [/.*(hardware|garage|mechanic|industrial|factory|fabrica|warehouse|armazem|power_plant|workshop|oficina|metro|construction|obra|lab).*/, 0.35, [1, 3],
      { essencial: 6, create_forca: 10, create_prensa: 10, create_producao: 8, create_avancado: 5, engenharia: 8, ferraria: 10,
        eletronica: 6, mecanica: 8, construcao: 4, marcenaria: 4 }],
    // kitchens, diners, supermarkets, farms
    [/.*(kitchen|cozinha|diner|restaurant|supermarket|mercado|farm|fazenda|bakery|padaria).*/, 0.30, [1, 3],
      { essencial: 6, culinaria: 20, sobrevivencia: 4, tecidos: 3 }],
    // homes, bedrooms, offices, schools, libraries, shops
    [/.*(house|home|casa|residen|apartment|bedroom|office|escritorio|school|escola|library|biblioteca|livraria|clothing|shop|store|loja).*/, 0.30, [1, 3],
      { essencial: 8, marcenaria: 10, construcao: 10, decoracao: 12, tecidos: 8, culinaria: 4, sobrevivencia: 4, eletronica: 2 }],
    // hospitals and pharmacies
    [/.*(hospital|clinic|pharmacy|farmacia).*/, 0.35, [1, 3], { essencial: 8, enfermagem: 20, sobrevivencia: 2 }],
    // police, military, prison, firefighters
    [/.*(police|policia|military|militar|army|bunker|prison|presidio|batalhao|fire_station|bombeiros|story).*/, 0.30, [1, 3],
      { essencial: 6, seguranca: 16, sobrevivencia: 8, eletronica: 4, mecanica: 4, ferraria: 4 }],
  ]

  LootJS.modifiers(event => {
    PLACES.forEach(p => {
      event.addLootTableModifier(p[0])
        .randomChance(p[1])
        .addWeightedLoot(p[2], weighted(p[3]))
    })
    // any other chest (ruins, mineshafts, mod structures...): one note, any subject
    event.addLootTypeModifier(LootType.CHEST)
      .randomChance(0.12)
      .addWeightedLoot(weighted({ essencial: 6 }))
  })
})()
